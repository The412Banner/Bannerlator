#!/bin/sh
# Rebuild gen/shaders/*.spv.h from shaders/*.comp (same flags as WinNative's wfg/CMakeLists.txt).
# The headers are committed; run this by hand after changing a shader. Needs glslc.
set -e
cd "$(dirname "$0")"
for f in shaders/*.comp; do
  b=$(basename "$f" .comp); v="${b}_comp"
  glslc --target-env=vulkan1.1 -O "$f" -o "/tmp/$v.spv"
  python3 - "/tmp/$v.spv" "gen/shaders/$v.spv.h" "$v" <<'PY'
import struct, sys
data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
out = ['// Generated by gen_shaders.sh from shaders/%s. Do not edit.' % sys.argv[3].replace('_comp', '.comp'),
       '#pragma once', '#include <stdint.h>', '#include <stddef.h>', '',
       'static const uint32_t %s[] = {' % sys.argv[3]]
for i in range(0, len(words), 8):
    out.append('    ' + ' '.join('0x%08x,' % w for w in words[i:i + 8]))
out += ['};', 'static const size_t %s_size = sizeof(%s);' % (sys.argv[3], sys.argv[3]), '']
open(sys.argv[2], 'w').write('\n'.join(out))
PY
  rm -f "/tmp/$v.spv"
done
